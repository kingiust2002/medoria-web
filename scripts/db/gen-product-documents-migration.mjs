#!/usr/bin/env node
// Generates migrations/48_product_documents.sql: product documents (brochure, datasheet, certificate, manual) for each house, written out explicitly
// from ONE template (so the two houses can never drift apart and the owner can read the exact SQL).
//
//   node scripts/db/gen-product-documents-migration.mjs          → rewrites migrations/48_product_documents.sql
//   node scripts/db/gen-product-documents-migration.mjs --check  → exits 1 if the committed file differs from the template
//
// tests/product-documents-migration.test.mjs runs the --check mode, so editing the SQL by hand (instead of the template) fails CI.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "migrations/48_product_documents.sql");

const HEAD = `-- ════════════════════════════════════════════════════════════════════════════
-- Medoria — Migration 48: product documents (Health and Beauty, separate)
--
-- GENERATED by scripts/db/gen-product-documents-migration.mjs from one template — edit the template, not this file.
--
-- For each house:
--   product_documents / beauty_product_documents   one row per document of ONE product: kind (brochure | datasheet | certificate | manual | other),
--       a title, the language of the document, an optional "valid until" date (a certificate that has lapsed is not shown), the stored file
--       (path inside the house's own image bucket, folder documents/), its size and SHA-256, whether it is published, a version (the panel's lock).
--   public_product_documents(product) / public_beauty_product_documents(product)   what the public product page may show: the PUBLISHED, still valid
--       documents of an ACTIVE product (never a variant), public columns only (no hash, no who-uploaded, no drafts).
--
-- The table itself is PRIVATE: row level security on, no policy, nothing for anon / authenticated. Only service_role (the panel actions) reads and writes.
-- A document's product, file and hash never change (a replacement is a new document); the version bumps on every update; a product that still has
-- documents cannot be deleted (ON DELETE RESTRICT — delete the documents first, the panel says so).
-- Needs migration 34 (operator_users) and the product tables of both houses. One transaction; idempotent; a self-check at the end aborts (rolls back) on any mismatch.
--
-- Rollback (only after the deployed code no longer uses it):
--   DROP FUNCTION public.public_product_documents(BIGINT), public.public_beauty_product_documents(BIGINT);
--   DROP TABLE public.product_documents, public.beauty_product_documents;  DROP FUNCTION public.product_documents_guard();
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.operator_users') IS NULL THEN
    RAISE EXCEPTION 'migration 48 needs migration 34 first (operator_users is missing)';
  END IF;
  IF to_regclass('public.products') IS NULL OR to_regclass('public.beauty_products') IS NULL THEN
    RAISE EXCEPTION 'migration 48 needs the product tables of both houses (products, beauty_products)';
  END IF;
END $$;

-- one guard function for both tables
CREATE OR REPLACE FUNCTION public.product_documents_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.product_id <> OLD.product_id OR NEW.file_path <> OLD.file_path OR NEW.sha256 <> OLD.sha256 OR NEW.id <> OLD.id THEN
    RAISE EXCEPTION 'documents:product_file_and_hash_are_fixed' USING ERRCODE = 'P0001';
  END IF;
  NEW.version := OLD.version + 1;
  NEW.updated_at := NOW();
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.product_documents_guard() FROM PUBLIC, anon, authenticated;
`;

const HOUSE = `
-- ── {h} ─────────────────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.{T} (
  id            BIGSERIAL PRIMARY KEY,
  product_id    BIGINT NOT NULL REFERENCES public.{PT} (id) ON DELETE RESTRICT,
  kind          TEXT NOT NULL CHECK (kind IN ('brochure', 'datasheet', 'certificate', 'manual', 'other')),
  title         TEXT NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 160),
  lang          TEXT CHECK (lang IS NULL OR lang IN ('fa', 'tg', 'ru', 'en')),
  valid_until   DATE,
  file_path     TEXT NOT NULL CHECK (char_length(file_path) BETWEEN 5 AND 300 AND file_path ~ '^documents/[A-Za-z0-9._-]+$'),
  file_size     INT NOT NULL CHECK (file_size BETWEEN 1 AND 20971520),
  sha256        TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  is_published  BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order    INT NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN -100000 AND 100000),
  version       INT NOT NULL DEFAULT 1,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by    UUID REFERENCES public.operator_users (id) ON DELETE SET NULL,
  updated_label TEXT CHECK (updated_label IS NULL OR char_length(updated_label) <= 80),
  CONSTRAINT {T}_file_unique UNIQUE (file_path)
);
CREATE UNIQUE INDEX IF NOT EXISTS {T}_product_hash ON public.{T} (product_id, sha256);
CREATE INDEX IF NOT EXISTS {T}_product ON public.{T} (product_id, sort_order, id);

DROP TRIGGER IF EXISTS {T}_guard ON public.{T};
CREATE TRIGGER {T}_guard BEFORE UPDATE ON public.{T} FOR EACH ROW EXECUTE FUNCTION public.product_documents_guard();

ALTER TABLE public.{T} ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.{T} FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.{T} TO service_role;
GRANT USAGE ON SEQUENCE public.{T}_id_seq TO service_role;

-- what the public product page may show: published, still valid, of an ACTIVE product that is not a variant; public columns only
CREATE OR REPLACE FUNCTION public.{FN}(p_product BIGINT)
RETURNS TABLE (id BIGINT, kind TEXT, title TEXT, lang TEXT, valid_until DATE, file_path TEXT, file_size INT)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT d.id, d.kind, d.title, d.lang, d.valid_until, d.file_path, d.file_size
    FROM public.{T} d
    JOIN public.{PT} p ON p.id = d.product_id
   WHERE d.product_id = p_product
     AND d.is_published
     AND (d.valid_until IS NULL OR d.valid_until >= (NOW() AT TIME ZONE 'Asia/Dushanbe')::date)
     AND p.is_active
     AND (to_jsonb(p) ->> 'variant_of') IS NULL
   ORDER BY d.sort_order, d.id
   LIMIT 50;
$$;
REVOKE ALL ON FUNCTION public.{FN}(BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.{FN}(BIGINT) TO anon, authenticated, service_role;
`;

const TAIL = `
-- self-check
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['product_documents', 'beauty_product_documents'] LOOP
    IF to_regclass('public.' || t) IS NULL THEN RAISE EXCEPTION 'migration 48 self-check failed: % is missing', t; END IF;
    IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = ('public.' || t)::regclass) THEN RAISE EXCEPTION 'migration 48 self-check failed: row-level security is off on %', t; END IF;
    IF (SELECT count(*) FROM pg_policies WHERE schemaname = 'public' AND tablename = t) <> 0 THEN RAISE EXCEPTION 'migration 48 self-check failed: % must have no policy', t; END IF;
    IF has_table_privilege('anon', 'public.' || t, 'SELECT') OR has_table_privilege('authenticated', 'public.' || t, 'SELECT')
       OR has_table_privilege('anon', 'public.' || t, 'INSERT') OR has_table_privilege('authenticated', 'public.' || t, 'UPDATE') THEN
      RAISE EXCEPTION 'migration 48 self-check failed: a public role can reach %', t;
    END IF;
    IF NOT has_table_privilege('service_role', 'public.' || t, 'UPDATE') THEN RAISE EXCEPTION 'migration 48 self-check failed: service_role cannot write %', t; END IF;
  END LOOP;
  IF NOT has_function_privilege('anon', 'public.public_product_documents(bigint)', 'EXECUTE') OR NOT has_function_privilege('anon', 'public.public_beauty_product_documents(bigint)', 'EXECUTE') THEN
    RAISE EXCEPTION 'migration 48 self-check failed: the public functions are not executable by anon';
  END IF;
END $$;

COMMIT;
`;

export function generate() {
  const houses = [["health", "product_documents", "products", "public_product_documents"], ["beauty", "beauty_product_documents", "beauty_products", "public_beauty_product_documents"]];
  return HEAD + houses.map(([h, T, PT, FN]) => HOUSE.replaceAll("{h}", h).replaceAll("{T}", T).replaceAll("{PT}", PT).replaceAll("{FN}", FN)).join("") + TAIL;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = generate();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== sql) { console.error("migrations/48_product_documents.sql differs from the template: run node scripts/db/gen-product-documents-migration.mjs"); process.exit(1); }
    console.log("migrations/48_product_documents.sql matches the template");
  } else {
    fs.writeFileSync(OUT, sql);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${sql.split("\n").length} lines)`);
  }
}
